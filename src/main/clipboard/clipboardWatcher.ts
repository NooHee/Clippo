import { MAX_TEXT_LENGTH, type ClipboardEntry, type ClipboardEntryType } from '../../shared/types';
import { fingerprintClipboardImage, type ImageClipboardReader } from './imageFingerprint';
import type { ClipboardChangeSource } from './clipboardChangeSource';

export interface WatchedClipboard extends ImageClipboardReader {
  readText(): string;
  has(format: string): boolean;
}

/**
 * Pasteboard types that password managers and other apps add to say "do not record this".
 * The convention is documented at http://nspasteboard.org and honoured by most clipboard managers.
 */
export const SENSITIVE_CLIPBOARD_TYPES: readonly string[] = [
  'org.nspasteboard.ConcealedType', // passwords, 2FA codes (1Password, Bitwarden, KeePassXC, ...)
  'org.nspasteboard.TransientType', // short-lived content that should not be kept
  'org.nspasteboard.AutoGeneratedType', // content an app put there without the user copying it
  'com.agilebits.onepassword', // older 1Password versions
  'de.petermaurer.TransientPasteboardType', // older transient marker, still used by some apps
];

export interface ClipboardWatcherDeps {
  clipboard: WatchedClipboard;
  history: { insert(content: string, type: ClipboardEntryType, imageName?: string): ClipboardEntry };
  /** Persists the image currently on the clipboard and returns its file name. */
  saveImage: (fingerprint: string) => string | null;
  ignoredApps: () => readonly string[];
  /** Resolves the name of the frontmost application, without blocking the main thread. */
  frontmostAppName: () => Promise<string | null>;
  onNewEntry: (entry: ClipboardEntry) => void;
  /**
   * Reports clipboard changes without reading the content (macOS). When absent, or when it stops
   * working, the watcher polls the content instead.
   */
  changeSource?: ClipboardChangeSource;
  platform?: string;
  logger?: Pick<Console, 'error'>;
}

/**
 * Watches the system clipboard for new text and images.
 *
 * Electron has no clipboard change notification, so there are two modes:
 *  - change events (macOS): a ClipboardChangeSource watches the pasteboard change counter and the
 *    watcher reads the clipboard only after it changed. While idle, Clippo reads nothing.
 *  - polling (fallback, Linux and Windows): every tick reads the text and the format list. Images
 *    are compared through a fingerprint of their raw bytes instead of being decoded each tick.
 *    Ticks are chained with setTimeout so a slow tick can never overlap the next one.
 * Both modes run the same `checkNow`, so detection behaves identically.
 */
export class ClipboardWatcher {
  private lastText = '';
  private lastImageFingerprint: string | null = null;
  private timer: ReturnType<typeof setTimeout> | null = null;
  private running = false;
  private intervalMs = 500;
  private mode: 'events' | 'polling' = 'polling';
  private checking: Promise<void> | null = null;
  private recheckRequested = false;

  constructor(private readonly deps: ClipboardWatcherDeps) {}

  start(intervalMs: number): void {
    if (this.running) return;
    this.intervalMs = intervalMs;
    this.running = true;
    this.rememberCurrentContent();
    if (this.deps.changeSource) this.startChangeEvents(this.deps.changeSource);
    else this.startPolling();
  }

  stop(): void {
    this.running = false;
    this.deps.changeSource?.stop();
    this.clearTimer();
  }

  /** Applies immediately when idle; a tick in progress picks it up when it schedules the next one. */
  updateInterval(intervalMs: number): void {
    this.intervalMs = intervalMs;
    if (!this.running) return;
    if (this.mode === 'events' && this.deps.changeSource) {
      this.startChangeEvents(this.deps.changeSource);
      return;
    }
    if (this.timer === null) return;
    this.clearTimer();
    this.scheduleNextTick();
  }

  /** Current detection mode, exposed for diagnostics and tests. */
  get detectionMode(): 'events' | 'polling' {
    return this.mode;
  }

  /**
   * Must be called right after Clippo itself writes to the clipboard, so that pasting an
   * entry does not get recorded again as a brand new entry on the next tick.
   */
  rememberCurrentContent(): void {
    this.lastText = this.deps.clipboard.readText();
    this.lastImageFingerprint = this.fingerprint();
  }

  /** Runs one detection pass. Public so tests can drive the watcher without timers. */
  async checkNow(): Promise<void> {
    if (this.isSensitive()) {
      // Remember it so the same content is not reconsidered on every tick, and is not recorded
      // if the marker is later removed while the content stays.
      this.rememberCurrentContent();
      return;
    }

    const imageFingerprint = this.fingerprint();
    if (imageFingerprint !== null && imageFingerprint !== this.lastImageFingerprint) {
      this.lastImageFingerprint = imageFingerprint;
      if (await this.copiedFromIgnoredApp()) return;
      const imageName = this.deps.saveImage(imageFingerprint);
      if (imageName) this.deps.onNewEntry(this.deps.history.insert(imageName, 'image', imageName));
      return;
    }

    const text = this.deps.clipboard.readText();
    if (!text || text === this.lastText) return;
    this.lastText = text;
    this.lastImageFingerprint = null; // The same image copied again later must be recorded.
    if (text.length > MAX_TEXT_LENGTH) return;
    if (await this.copiedFromIgnoredApp()) return;
    this.deps.onNewEntry(this.deps.history.insert(text, 'text'));
  }

  private isSensitive(): boolean {
    return SENSITIVE_CLIPBOARD_TYPES.some((format) => {
      try {
        return this.deps.clipboard.has(format);
      } catch {
        return false;
      }
    });
  }

  private startChangeEvents(source: ClipboardChangeSource): void {
    this.mode = 'events';
    source.start(this.intervalMs, {
      onChange: () => this.requestCheck(),
      onUnavailable: (reason) => {
        if (!this.running) return;
        this.logger.error('[Clippo] Clipboard change events unavailable, falling back to polling', reason);
        this.startPolling();
      },
    });
  }

  private startPolling(): void {
    this.mode = 'polling';
    this.clearTimer();
    this.scheduleNextTick();
  }

  /**
   * Runs a check now, or once more after the one in progress if a change arrives meanwhile.
   * Checks never overlap, and a burst of changes costs at most two checks.
   */
  private requestCheck(): void {
    if (this.checking) {
      this.recheckRequested = true;
      return;
    }
    this.checking = this.checkNow()
      .catch((error: unknown) => this.logger.error('[Clippo] Clipboard check failed', error))
      .finally(() => {
        this.checking = null;
        if (this.recheckRequested && this.running) {
          this.recheckRequested = false;
          this.requestCheck();
        }
      });
  }

  private get logger(): Pick<Console, 'error'> {
    return this.deps.logger ?? console;
  }

  private fingerprint(): string | null {
    return fingerprintClipboardImage(this.deps.clipboard, this.deps.platform);
  }

  private async copiedFromIgnoredApp(): Promise<boolean> {
    const ignoredApps = this.deps.ignoredApps();
    if (ignoredApps.length === 0) return false;
    const activeApp = (await this.deps.frontmostAppName())?.toLowerCase();
    return activeApp !== undefined && ignoredApps.some((app) => app.toLowerCase() === activeApp);
  }

  private scheduleNextTick(): void {
    this.timer = setTimeout(() => {
      this.timer = null;
      this.checkNow()
        .catch((error: unknown) => this.logger.error('[Clippo] Clipboard check failed', error))
        .finally(() => {
          if (this.running) this.scheduleNextTick();
        });
    }, this.intervalMs);
  }

  private clearTimer(): void {
    if (this.timer !== null) clearTimeout(this.timer);
    this.timer = null;
  }
}
